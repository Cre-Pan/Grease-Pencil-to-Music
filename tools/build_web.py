"""Build the installable web app (PWA) from web/app.html.

    python tools/build_web.py        # -> docs/app/ (served by GitHub Pages from /docs)

web/app.html is the page body (the same file is published as a claude.ai artifact).
This wraps it in a full document with the Home Screen metadata, writes the web app
manifest, the icons and a service worker that keeps everything for offline use.
"""

import hashlib
import json
import math
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "web" / "app.html"
OUT = ROOT / "docs" / "app"
NAME = "Grease Pencil to Music"
SHORT = "GP Music"

HEAD = """<!doctype html>
<html lang="it">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{name}</title>
<meta name="description" content="Disegna musica con la Apple Pencil: tavola, beat, MIDI ed export.">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="{short}">
<meta name="theme-color" content="#f2f2f7" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#000000" media="(prefers-color-scheme: dark)">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icon-180.png">
<link rel="icon" type="image/png" href="icon-192.png">
<style>
:root {{ color-scheme: light; padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }}
body {{ margin: 0; font: 14px system-ui, -apple-system, sans-serif; }}
img {{ max-width: 100%; }}
[hidden] {{ display: none !important; }}
</style>
</head>
<body>
"""

SERVICE_WORKER = """// Generated by tools/build_web.py: keeps the app available offline.
const CACHE = "gp2m-{version}";
const FILES = ["./", "./index.html", "./manifest.webmanifest", "./icon-180.png", "./icon-192.png", "./icon-512.png", "./icon-maskable.png"];
self.addEventListener("install", event => {{
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", event => {{
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith("gp2m-") && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener("fetch", event => {{
  if (event.request.method !== "GET" || new URL(event.request.url).origin !== location.origin) return;
  event.respondWith(caches.match(event.request, {{ ignoreSearch: true }}).then(hit => hit || fetch(event.request)));
}});
"""


def icon(size, maskable=False):
    """The app icon: Apple-style gradient, faint staff and a drawn musical line."""
    from PIL import Image, ImageDraw
    big = 1024
    img = Image.new("RGB", (big, big))
    top, bottom = (94, 92, 230), (255, 55, 95)  # indigo -> pink
    px = img.load()
    for y in range(big):
        for x in range(big):
            t = min(1.0, max(0.0, (x * 0.35 + y * 0.65) / big))
            px[x, y] = tuple(int(a + (b - a) * t) for a, b in zip(top, bottom))
    draw = ImageDraw.Draw(img, "RGBA")
    pad = 230 if maskable else 150
    for k in range(5):  # staff
        y = pad + 120 + k * (big - 2 * pad - 240) / 4
        draw.line([(pad, y), (big - pad, y)], fill=(255, 255, 255, 70), width=10)
    points = []
    for i in range(240):  # the drawn line: a phrase that rises and falls
        u = i / 239
        x = pad + u * (big - 2 * pad)
        y = big / 2 - math.sin(u * math.pi * 1.6 - 0.3) * (big - 2 * pad) * 0.26
        r = 22 + 26 * math.sin(math.pi * u) ** 0.7  # thickness follows the pressure
        points.append((x, y, r))
    for x, y, r in points:
        draw.ellipse([x - r, y - r, x + r, y + r], fill=(255, 255, 255, 255))
    for x, y in [(pad + 40, big - pad - 90), (big - pad - 60, pad + 70)]:
        draw.ellipse([x - 34, y - 34, x + 34, y + 34], fill=(255, 255, 255, 230))
    return img.resize((size, size), Image.LANCZOS)


def build(out=OUT):
    body = SOURCE.read_text(encoding="utf-8")
    body = re.sub(r"^\s*<title>.*?</title>\s*", "", body, count=1, flags=re.S)
    body = re.sub(r'^\s*<meta name="claude:[^>]*>\s*', "", body, count=1)
    out.mkdir(parents=True, exist_ok=True)
    page = HEAD.format(name=NAME, short=SHORT) + body + "\n</body>\n</html>\n"
    (out / "index.html").write_text(page, encoding="utf-8")
    manifest = {
        "name": NAME, "short_name": SHORT, "lang": "it", "start_url": "./", "scope": "./",
        "display": "standalone", "orientation": "any",
        "background_color": "#000000", "theme_color": "#000000",
        "description": "Disegna musica con la Apple Pencil: tavola, beat, MIDI ed export.",
        "icons": [
            {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "icon-maskable.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        ],
    }
    (out / "manifest.webmanifest").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    for size in (180, 192, 512):
        icon(size).save(out / f"icon-{size}.png")
    icon(512, maskable=True).save(out / "icon-maskable.png")
    version = hashlib.sha256(page.encode()).hexdigest()[:12]
    (out / "sw.js").write_text(SERVICE_WORKER.format(version=version), encoding="utf-8")
    docs = out.parent
    (docs / ".nojekyll").write_text("", encoding="utf-8")
    (docs / "index.html").write_text(
        '<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=app/">'
        '<title>Grease Pencil to Music</title><a href="app/">Apri la web app</a>\n', encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build())
    sys.exit(0)
