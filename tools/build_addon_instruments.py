"""Write grease_pencil_to_music/web_instruments.py: the web app's instrument list for the add-on.

    python tools/build_addon_instruments.py

Reads ``INSTRUMENTS``, ``SAMPLE_ZONES``, the families and the colours from web/app.html, and
the length of every recorded hit from docs/app/samples (needs ffmpeg). Run it again after
tools/build_samples.py or after a change to the web app's instrument list. The recordings
themselves are not copied: tools/build_zip.py puts docs/app/samples and docs/app/rooms in the
add-on zip.
"""

import json
import pathlib
import pprint
import re
import subprocess
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = ROOT / "web" / "app.html"
SAMPLES = ROOT / "docs" / "app" / "samples"
OUT = ROOT / "grease_pencil_to_music" / "web_instruments.py"
SR = 44100


def _js_object(text):
    """A JS object literal of INSTRUMENTS as a Python dict (keys unquoted, strings quoted)."""
    text = re.sub(r"([{,]\s*)([A-Za-z_]\w*)\s*:", r'\1"\2":', text)
    return json.loads(text)


def _hex_rgba(value):
    value = value.lstrip("#")
    return tuple(round(int(value[i:i + 2], 16) / 255, 3) for i in (0, 2, 4)) + (1.0,)


def _families(html, name):
    block = re.search(rf"const {name} = \[(.*?)\n\];", html, re.S).group(1)
    return [(title, ids.replace('"', "").replace(" ", "").split(","))
            for title, ids in re.findall(r'\["([^"]+)", \[([^\]]*)\]\]', block)]


def _hit_length(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR),
                          "-f", "f32le", "-"], check=True, capture_output=True).stdout
    x = np.frombuffer(raw, dtype=np.float32)
    peak = float(np.max(np.abs(x))) or 1.0
    onset = int(np.argmax(np.abs(x) > peak * 0.02))
    return round((len(x) - onset) / SR, 3)


def main():
    html = APP.read_text(encoding="utf-8")
    sys_block = re.search(r"const SYS = \{(.*?)\n\};", html, re.S).group(1)
    colours = {k: _hex_rgba(light)
               for k, light in re.findall(r'(\w+): \["(#[0-9A-Fa-f]{6})"', sys_block)}
    block = re.search(r"const INSTRUMENTS = \[(.*?)\n\];", html, re.S).group(1)
    instruments = [_js_object(line.strip().rstrip(","))
                   for line in block.splitlines() if line.strip().startswith("{")]
    zones = json.loads(re.search(r"const SAMPLE_ZONES = (\{.*?\});", html).group(1))
    rows = []
    for inst in instruments:
        ident = inst["id"]
        row = {"id": ident, "name": inst["name"], "color": colours[inst["c"]],
               "gm": inst.get("gm", -1), "rel": inst.get("rel", 0.0), "kind": inst.get("kind", ""),
               "drum": inst.get("drum", 0), "sus": bool(inst.get("sus")),
               "hold": bool(inst.get("hold")),
               "zones": zones.get(ident, []) if inst.get("smp") else [],
               "length": 0.0}
        if row["zones"] == [0]:
            row["length"] = _hit_length(SAMPLES / ident / "0.mp3")
        rows.append(row)
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        '"""The web app\'s instruments.',
        "",
        "Generated by tools/build_addon_instruments.py: do not edit.",
        "",
        "``zones``: MIDI notes recorded in ``sounds/samples/<id>/<note>.mp3`` ([0] = one hit);",
        "``length``: seconds of a recorded hit. Pure Python: no ``bpy`` import.",
        '"""',
        "",
        "INSTRUMENTS = (",
    ]
    for row in rows:
        text = pprint.pformat(row, width=95, compact=True, sort_dicts=False)
        lines += ["    " + line for line in text.splitlines()]
        lines[-1] += ","
    lines += [")", "", "MELODIC_FAMILIES = ("]
    for name in ("MEL_FAMILIES", "DRUM_FAMILIES"):
        if name == "DRUM_FAMILIES":
            lines += [")", "", "DRUM_FAMILIES = ("]
        for title, ids in _families(html, name):
            text = pprint.pformat((title, tuple(ids)), width=95, compact=True)
            lines += ["    " + line for line in text.splitlines()]
            lines[-1] += ","
    lines += [")", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUT, len(rows), "instruments")


if __name__ == "__main__":
    sys.exit(main())
