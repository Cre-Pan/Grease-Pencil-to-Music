SPACING = 0.16


def _advance(char):
    strokes = GLYPHS.get(char)
    if not strokes:
        return 0.4
    return max(x for stroke in strokes for x, _y in stroke) + SPACING


def text_width(text, height):
    if not text:
        return 0.0
    return (sum(_advance(c) for c in text) - SPACING) * height


def text_polylines(text, x, y, height, align="LEFT"):
    """Polylines for ``text`` with its baseline at ``y``.

    ``align`` is LEFT, CENTER or RIGHT relative to ``x``.
    """
    width = text_width(text, height)
    if align == "CENTER":
        x -= width / 2.0
    elif align == "RIGHT":
        x -= width
    lines = []
    cursor = x
    for char in text:
        for stroke in GLYPHS.get(char, ()):
            lines.append([(cursor + gx * height, y + gy * height) for gx, gy in stroke])
        cursor += _advance(char) * height
    return lines
